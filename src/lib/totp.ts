import { timingSafeEqual } from './securityGuard';

const BASE32_ALPHABET = 'ABCDEFGHIJKLMNOPQRSTUVWXYZ234567';

/**
 * Generates a 160-bit (20-byte) cryptographically random Base32 secret
 * compliant with Google Authenticator, Microsoft Authenticator, Authy & RFC 4226/6238.
 */
export function generateTotpBase32Secret(byteLength = 20): string {
  const bytes = new Uint8Array(byteLength);
  if (typeof globalThis !== 'undefined' && globalThis.crypto?.getRandomValues) {
    globalThis.crypto.getRandomValues(bytes);
  } else {
    for (let i = 0; i < byteLength; i++) {
      bytes[i] = Math.floor(Math.random() * 256);
    }
  }

  let bits = 0;
  let value = 0;
  let output = '';
  for (let i = 0; i < bytes.length; i++) {
    value = (value << 8) | bytes[i];
    bits += 8;
    while (bits >= 5) {
      output += BASE32_ALPHABET[(value >>> (bits - 5)) & 31];
      bits -= 5;
    }
  }
  if (bits > 0) {
    output += BASE32_ALPHABET[(value << (5 - bits)) & 31];
  }
  return output;
}

export function formatTotpSecretForDisplay(secret: string): string {
  const clean = secret.toUpperCase().replace(/[^A-Z2-7]/g, '');
  return clean.replace(/(.{4})/g, '$1 ').trim();
}

export function decodeBase32ToBytes(secretBase32: string): Uint8Array {
  const clean = secretBase32.toUpperCase().replace(/[\s=-]+/g, '');
  const bytes: number[] = [];
  let bits = 0;
  let value = 0;

  for (let i = 0; i < clean.length; i++) {
    const idx = BASE32_ALPHABET.indexOf(clean[i]);
    if (idx === -1) continue;
    value = (value << 5) | idx;
    bits += 5;
    if (bits >= 8) {
      bytes.push((value >>> (bits - 8)) & 0xff);
      bits -= 8;
    }
  }
  return new Uint8Array(bytes);
}

export function buildTotpOtpAuthUri(params: {
  secret: string;
  accountEmail: string;
  issuer?: string;
}): string {
  const issuer = (params.issuer || 'Acash Admin').trim();
  const label = `${encodeURIComponent(issuer)}:${encodeURIComponent(params.accountEmail.trim().toLowerCase())}`;
  const cleanSecret = params.secret.toUpperCase().replace(/[^A-Z2-7]/g, '');
  return `otpauth://totp/${label}?secret=${cleanSecret}&issuer=${encodeURIComponent(issuer)}&algorithm=SHA1&digits=6&period=30`;
}

export async function generateTotpCode(
  secretBase32: string,
  timestampMs = Date.now(),
  stepOffset = 0
): Promise<string> {
  const keyBytes = decodeBase32ToBytes(secretBase32);
  if (keyBytes.length === 0) {
    throw new Error('Invalid TOTP Base32 secret.');
  }
  if (typeof globalThis === 'undefined' || !globalThis.crypto?.subtle) {
    throw new Error('Web Crypto SubtleCrypto is unavailable in this browser.');
  }

  const counter = Math.floor(timestampMs / 1000 / 30) + stepOffset;
  const counterBytes = new Uint8Array(8);
  let tmp = counter;
  for (let i = 7; i >= 0; i--) {
    counterBytes[i] = tmp & 0xff;
    tmp = Math.floor(tmp / 256);
  }

  const keyCopy = new Uint8Array(keyBytes.byteLength);
  keyCopy.set(keyBytes);

  const cryptoKey = await globalThis.crypto.subtle.importKey(
    'raw',
    keyCopy.buffer,
    { name: 'HMAC', hash: 'SHA-1' },
    false,
    ['sign']
  );

  const hmacBuf = await globalThis.crypto.subtle.sign('HMAC', cryptoKey, counterBytes.buffer);
  const hmac = new Uint8Array(hmacBuf);
  const offset = hmac[hmac.length - 1] & 0x0f;
  const binaryCode =
    ((hmac[offset] & 0x7f) << 24) |
    ((hmac[offset + 1] & 0xff) << 16) |
    ((hmac[offset + 2] & 0xff) << 8) |
    (hmac[offset + 3] & 0xff);

  const otp = binaryCode % 1_000_000;
  return String(otp).padStart(6, '0');
}

/**
 * Verifies a 6-digit code generated by Google Authenticator, Microsoft Authenticator,
 * Authy, 1Password, or any RFC 6238 TOTP app with +-30s clock-skew tolerance.
 */
export async function verifyTotpCode(
  secretBase32: string,
  candidateCode: string,
  windowSteps = 1,
  timestampMs = Date.now()
): Promise<boolean> {
  const cleanCode = candidateCode.replace(/\s+/g, '').trim();
  if (!/^\d{6}$/.test(cleanCode) || !secretBase32) {
    return false;
  }

  for (let offset = -windowSteps; offset <= windowSteps; offset++) {
    try {
      const expected = await generateTotpCode(secretBase32, timestampMs, offset);
      if (timingSafeEqual(expected, cleanCode)) {
        return true;
      }
    } catch {
      return false;
    }
  }
  return false;
}
